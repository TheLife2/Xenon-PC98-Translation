def main():
    lines = open(C.TRANSLATION, encoding="utf-8").read().split("\n")
    hit = miss = 0
    used = set()
    i = 0
    while i < len(lines):
        if lines[i].startswith("//"):
            jp = lines[i]  [2:]
            if jp in SEED:
                j = i + 1
                while j < len(lines) and lines[j].startswith("#"):
                    j += 1
                if j < len(lines):
                    lines[j] = SEED[jp]
                    hit += 1
                    used.add(jp)
        i += 1
    open(C.TRANSLATION, "w", encoding="utf-8", newline="\n").write("\n".join(lines))
    for k in SEED:
        if k not in used:
            miss += 1
            print("  키를 못 찾음:", k[:50])
    print(f"시드 반영 {hit}개 / 미매칭 {miss}개")


if __name__ == "__main__":
    main()
